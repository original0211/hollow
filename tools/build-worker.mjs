#!/usr/bin/env node
// Build the single-file Worker bundle (worker/src/index.js) by inlining the
// shared modules. The deployment path uploads one module via the API, so the
// bundle is committed next to its sources; rebuild after changing shared/ or
// worker/src/entry.js. Only relative imports are inlined; platform imports
// (node:crypto, cloudflare:sockets) stay as-is.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const parts = [
  "shared/vendor/noble-ciphers-chacha20poly1305.js",
  "shared/crypto.js",
  "shared/protocol.js",
  "shared/server-core.js",
  "worker/src/entry.js",
];

function transform(src) {
  // drop relative import statements (single or multi-line)
  src = src.replace(/import[\s\S]*?from\s*["']\.[^"']*["'];?/g, "");
  // drop standalone side-effect relative imports
  src = src.replace(/import\s*["']\.[^"']*["'];?/g, "");
  // drop export lists
  src = src.replace(/export\s*\{[^}]*\};?/g, "");
  // un-prefix inline exports (but keep `export default` intact)
  src = src.replace(/^export\s+(?=(const|let|var|function|async|class)\b)/gm, "");
  return src;
}

let out = "// Hollow Worker bundle — GENERATED by tools/build-worker.mjs; do not edit.\n" +
  "// Sources: shared/vendor/noble-ciphers-chacha20poly1305.js, shared/crypto.js, shared/protocol.js, shared/server-core.js, worker/src/entry.js\n";
for (const part of parts) {
  const src = fs.readFileSync(path.join(root, part), "utf8");
  out += `\n// ===== ${part} =====\n` + transform(src) + "\n";
}
fs.writeFileSync(path.join(root, "worker/src/index.js"), out);
console.log(`wrote worker/src/index.js (${out.length} bytes)`);
